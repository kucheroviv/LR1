def add(a: float, b: float) -> float:
    """Выполняет сложение двух чисел"""
    return a + b


def sub(a: float, b: float) -> float:
    """Выполняет вычитание"""
    return a - b


def mul(a, b):
    """Выполняет умножение"""
    return a * b


def div(a, b):
    """Выполняет деление"""
    return a / b


def neg(a):
    """Возвращает число с противоположным знаком"""
    return -a


def sqr(a):
    """Возводит число в квадрат"""
    return a * a


def power(a, b):
    """Возводит число a в степень b"""
    return a ** b