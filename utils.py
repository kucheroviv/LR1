def add(a: float, b: float) -> float:
    """Выполняет сложение двух чисел"""
    return a + b


def sub(a: float, b: float) -> float:
    """Выполняет вычитание"""
    return a - b

def mul(a, b):
    return a * b


def div(a, b):
    return a / b


def neg(a):
    return -a

def sqr(a):
    return a*a
